import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {createVoltaraAuth} from '../lib/auth-options.ts';
import {safeReturnTo} from '../lib/return-to.ts';
test('registration, verified login, session, reset and revocation with real auth and SQLite',async()=>{
 const database=new DatabaseSync(':memory:');database.exec(readFileSync(new URL('../drizzle/0001_auth.sql',import.meta.url),'utf8'));
 const sent=[];const baseURL='http://localhost:3456';
 const auth=createVoltaraAuth({database,secret:'test-only-secret-32-characters-long-123456789',baseURL,sendEmail:async(to,subject,url)=>{sent.push({to,subject,url});}});
 const request=(path,body,cookie)=>auth.handler(new Request(baseURL+'/api/auth/'+path,{method:'POST',headers:{origin:baseURL,'cf-connecting-ip':'192.0.2.1','content-type':'application/json',...(cookie?{cookie}:{})},body:JSON.stringify(body)}));
 const identity={name:'Test Owner',email:'owner@example.test',password:'Test-passphrase-1234'};
 let response=await request('sign-up/email',{...identity,callbackURL:'/login'});assert.equal(response.status,200,await response.clone().text());assert.equal(sent.length,1);
 response=await request('sign-in/email',identity);assert.equal(response.status,403);
 const verified=await auth.handler(new Request(sent[0].url));assert.ok(verified.status===200||verified.status===302);
 response=await request('sign-in/email',identity);assert.equal(response.status,200,await response.clone().text());
 const cookie=response.headers.getSetCookie().map(x=>x.split(';')[0]).join('; ');assert.ok(cookie);
 let session=await auth.api.getSession({headers:new Headers({cookie})});assert.equal(session.user.email,identity.email);
 assert.equal(await auth.api.getSession({headers:new Headers({'oai-authenticated-user-id':'forged','oai-authenticated-user-email':identity.email})}),null);
 response=await request('request-password-reset',{email:identity.email,redirectTo:'/reset-password'});assert.equal(response.status,200);
 const resetURL=new URL(sent.at(-1).url);const token=resetURL.pathname.split('/').at(-1);
 response=await request('reset-password',{token,newPassword:'A-different-passphrase-1234'});assert.equal(response.status,200,await response.clone().text());
 assert.equal(await auth.api.getSession({headers:new Headers({cookie})}),null);
 assert.notEqual((await request('sign-in/email',identity)).status,200);
 assert.equal((await request('sign-in/email',identity)).status,429);
 database.exec('DELETE FROM rateLimit');
 response=await request('sign-in/email',{...identity,password:'A-different-passphrase-1234'});assert.equal(response.status,200);
 const cookie2=response.headers.getSetCookie().map(x=>x.split(';')[0]).join('; ');
 assert.equal((await request('sign-out',{},cookie2)).status,200);
 assert.equal(await auth.api.getSession({headers:new Headers({cookie:cookie2})}),null);
 database.close();
});
test('return URLs cannot leave Voltara',()=>{for(const value of ['https://evil.test','//evil.test','/\\evil.test','/api/auth/sign-out'])assert.equal(safeReturnTo(value),'/account');assert.equal(safeReturnTo('/transformer/#part=core'),'/transformer/#part=core');});
